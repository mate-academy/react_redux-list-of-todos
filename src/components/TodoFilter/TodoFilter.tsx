import React from 'react';
import { useAppDispatch, useAppSelector } from '../../app/hooks';
import { filterSlice } from '../../features/filter';
import { Status } from '../../types/Status';

export const TodoFilter: React.FC = () => {
  const dispatch = useAppDispatch();
  const { query, status } = useAppSelector(state => state.filter);

  const handlerSortStatus = (e: React.ChangeEvent<HTMLSelectElement>) => {
    const newStatus = e.target.value as Status;

    dispatch(filterSlice.actions.setSortStatus(newStatus));
  };

  const handlerFilterQuery = (e: React.ChangeEvent<HTMLInputElement>) => {
    dispatch(filterSlice.actions.setFilterQuery(e.target.value));
  };

  const handlerClearQuery = () => {
    dispatch(filterSlice.actions.setFilterQuery(''));
  };

  return (
    <form
      className="field has-addons"
      onSubmit={event => event.preventDefault()}
    >
      <p className="control">
        <span className="select">
          <select
            data-cy="statusSelect"
            onChange={handlerSortStatus}
            value={status}
          >
            <option value="all">All</option>
            <option value="active">Active</option>
            <option value="completed">Completed</option>
          </select>
        </span>
      </p>

      <p className="control is-expanded has-icons-left has-icons-right">
        <input
          value={query}
          data-cy="searchInput"
          type="text"
          className="input"
          placeholder="Search..."
          onChange={handlerFilterQuery}
        />
        <span className="icon is-left">
          <i className="fas fa-magnifying-glass" />
        </span>

        <span className="icon is-right" style={{ pointerEvents: 'all' }}>
          {/* eslint-disable-next-line jsx-a11y/control-has-associated-label */}
          {query.length > 0 && (
            <button
              data-cy="clearSearchButton"
              type="button"
              className="delete"
              onClick={handlerClearQuery}
            />
          )}
        </span>
      </p>
    </form>
  );
};
